def _describe_dataset(results):
    profile = results.get("profile_before") or {}
    if not profile:
        return ""
    return "\n".join([
        "## Dataset overview",
        "",
        _line("Rows", f"{profile['n_rows']:,}"),
        _line("Columns", profile["n_columns"]),
        _line("Numeric columns", len(profile["numeric_columns"])),
        _line("Categorical columns", len(profile["categorical_columns"])),
        _line("Date columns", len(profile["datetime_columns"])),
        _line("Duplicate rows", f"{profile['duplicate_rows']:,} ({profile['duplicate_pct']}%)"),
        _line("Missing cells", f"{profile['total_missing_cells']:,} ({profile['missing_pct']}% of all cells)"),
        _line("Size in memory", f"{profile['memory_mb']} MB"),
    ])


def _describe_quality(results):
    profile = results.get("profile_before") or {}
    if not profile:
        return ""
    lines = [
        "## Data quality",
        "",
        f"**Quality score: {profile['quality_score']}/100**",
        "",
    ]
    lines += [f"- {issue['message']}" for issue in profile["quality_issues"]]
    return "\n".join(lines)


def _describe_cleaning(results):
    report = results.get("cleaning") or {}
    if not report:
        return ""
    before, after = report["before"], report["after"]
    lines = [
        "## Cleaning performed",
        "",
        _table(["", "Before", "After"],
               [["Rows", f"{before['rows']:,}", f"{after['rows']:,}"],
                ["Columns", before["columns"], after["columns"]],
                ["Missing cells", f"{before['missing_cells']:,}", f"{after['missing_cells']:,}"],
                ["Duplicate rows", f"{before['duplicate_rows']:,}", f"{after['duplicate_rows']:,}"]]),
        "",
    ]
    if report["steps"]:
        lines += [f"- **{step['action']}.** {step['detail']}" for step in report["steps"]]
        lines += [""]
    lines += [f"*{report['missing_note']}*"]
    return "\n".join(lines)
